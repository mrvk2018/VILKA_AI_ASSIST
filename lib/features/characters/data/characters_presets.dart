/// Неизменяемые базовые характеры.
///
/// Привязанность и время последнего общения сюда не записываются:
/// сервис характеров хранит их поверх этих профилей.
abstract final class CharactersPresets {
  static const List<CharacterProfile> all = [
    CharacterProfile(
      id: 'moody_wife',
      name: 'Капризная и обидчивая',
      avatar: 'assets/characters/moody_wife.png',
      systemPrompt: _moody,
    ),
    CharacterProfile(
      id: 'street_wife',
      name: 'Уличная хабалка',
      avatar: 'assets/characters/street_wife.png',
      systemPrompt: _street,
    ),
    CharacterProfile(
      id: 'teacher_wife',
      name: 'Умная училка',
      avatar: 'assets/characters/teacher_wife.png',
      systemPrompt: _teacher,
    ),
    CharacterProfile(
      id: 'shy_wife',
      name: 'Стеснительная',
      avatar: 'assets/characters/shy_wife.png',
      systemPrompt: _shy,
    ),
  ];

  static bool contains(String id) => all.any((profile) => profile.id == id);

  static CharacterProfile byId(String id) {
    for (final profile in all) {
      if (profile.id == id) return profile;
    }
    throw ArgumentError.value(id, 'id', 'Неизвестный характер');
  }
}

